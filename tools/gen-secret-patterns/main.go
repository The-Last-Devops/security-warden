// Command gen-secret-patterns turns gitleaks' default rules into
// internal/source/secretpatterns_gen.go.
//
// Fetch the config at a release tag first (never at scan time):
//
//	tag=$(gh api repos/gitleaks/gitleaks/releases/latest -q .tag_name)
//	gh api "repos/gitleaks/gitleaks/contents/config/gitleaks.toml?ref=$tag" -q .content | base64 -d > /tmp/gitleaks.toml
//	cd tools && go run ./gen-secret-patterns -in /tmp/gitleaks.toml -tag "$tag" -out ../internal/source/secretpatterns_gen.go
//
// Secret patterns adapted from gitleaks (https://github.com/gitleaks/gitleaks),
// MIT License, Copyright (c) 2019 Zachary Rice.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/BurntSushi/toml"
)

type allowlist struct {
	Condition   string   `toml:"condition"`
	RegexTarget string   `toml:"regexTarget"`
	Regexes     []string `toml:"regexes"`
	Paths       []string `toml:"paths"`
	Commits     []string `toml:"commits"`
	Stopwords   []string `toml:"stopwords"`
}

type rule struct {
	ID          string      `toml:"id"`
	Regex       string      `toml:"regex"`
	Path        string      `toml:"path"`
	Entropy     float64     `toml:"entropy"`
	SecretGroup int         `toml:"secretGroup"`
	Keywords    []string    `toml:"keywords"`
	Allowlists  []allowlist `toml:"allowlists"`
	Allowlist   *allowlist  `toml:"allowlist"`
}

type config struct {
	Allowlist allowlist `toml:"allowlist"`
	Rules     []rule    `toml:"rules"`
}

// noisy rules: they match ordinary text or identifiers that are not secrets,
// or overlap checks the scanner already makes in a more precise way.
var noisy = map[string]string{
	"generic-api-key":        "matches any long value next to a key-like word",
	"jwt":                    "keyword \"ey\" is everywhere; JWTs are mostly short-lived",
	"jwt-base64":             "same as jwt",
	"curl-auth-header":       "covered by the bearer/password history checks",
	"curl-auth-user":         "covered by the password history check",
	"kubernetes-secret-yaml": "about YAML manifests, not tokens",
	"nuget-config-password":  "about nuget.config files",
	"hashicorp-tf-password":  "about Terraform files",
}

// identifiers: client IDs and public keys are not secrets on their own.
var identifier = regexp.MustCompile(`-(client|access|user-api)-id$|(^|-)pub(lic)?-(api-)?key$`)

func main() {
	in := flag.String("in", "", "gitleaks.toml")
	tag := flag.String("tag", "", "gitleaks release tag the file came from")
	out := flag.String("out", "", "output Go file")
	flag.Parse()
	if *in == "" || *tag == "" || *out == "" {
		log.Fatal("usage: gen-secret-patterns -in gitleaks.toml -tag vX.Y.Z -out file.go")
	}
	var c config
	if _, err := toml.DecodeFile(*in, &c); err != nil {
		log.Fatal(err)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen-secret-patterns from gitleaks %s; DO NOT EDIT.\n\n", *tag)
	b.WriteString("// Secret patterns adapted from gitleaks (https://github.com/gitleaks/gitleaks),\n// MIT License, Copyright (c) 2019 Zachary Rice.\n\npackage source\n\n")
	fmt.Fprintf(&b, "const secretPatternsVersion = %q\n\n", "gitleaks "+*tag)
	b.WriteString("// secretGlobalAllow lists values gitleaks never treats as secrets.\n")
	b.WriteString("var secretGlobalAllow = []string{\n")
	for _, r := range c.Allowlist.Regexes {
		if _, err := regexp.Compile(r); err == nil {
			fmt.Fprintf(&b, "\t%s,\n", quote(r))
		}
	}
	b.WriteString("}\n\nvar secretGlobalStopwords = []string{\n")
	for _, s := range c.Allowlist.Stopwords {
		fmt.Fprintf(&b, "\t%s,\n", quote(strings.ToLower(s)))
	}
	b.WriteString("}\n\nvar secretPatternList = []secretPattern{\n")

	kept, bad, skipped := 0, 0, 0
	var skippedIDs []string
	sort.Slice(c.Rules, func(i, j int) bool { return c.Rules[i].ID < c.Rules[j].ID })
	for _, r := range c.Rules {
		why := ""
		switch {
		case r.Regex == "":
			why = "path-only rule"
		case noisy[r.ID] != "":
			why = noisy[r.ID]
		case identifier.MatchString(r.ID):
			why = "identifier, not a secret"
		case len(r.Keywords) == 0:
			why = "no keywords to prefilter on"
		case strings.Contains(r.Regex, `\s\S`) || strings.Contains(r.Regex, `\n`) || strings.Contains(r.Regex, "(?s"):
			why = "spans several lines"
		}
		if why != "" {
			skipped++
			skippedIDs = append(skippedIDs, r.ID+" ("+why+")")
			continue
		}
		if _, err := regexp.Compile(r.Regex); err != nil {
			bad++
			skippedIDs = append(skippedIDs, r.ID+" (Go regexp: "+err.Error()+")")
			continue
		}
		lists := r.Allowlists
		if r.Allowlist != nil {
			lists = append(lists, *r.Allowlist)
		}
		var allow, allowMatch, stop []string
		for _, a := range lists {
			// Only checks on the secret or match itself apply here: there
			// are no commits, and the scanner knows what file it reads.
			if len(a.Paths) > 0 || len(a.Commits) > 0 || a.RegexTarget == "line" {
				continue
			}
			for _, x := range a.Regexes {
				if _, err := regexp.Compile(x); err != nil {
					continue
				}
				if a.RegexTarget == "match" {
					allowMatch = append(allowMatch, x)
				} else {
					allow = append(allow, x)
				}
			}
			for _, s := range a.Stopwords {
				stop = append(stop, strings.ToLower(s))
			}
		}
		kws := make([]string, 0, len(r.Keywords))
		for _, k := range r.Keywords {
			kws = append(kws, strings.ToLower(k))
		}
		fmt.Fprintf(&b, "\t{ID: %q, Regex: %s, Keywords: %s", r.ID, quote(r.Regex), list(kws))
		if r.Entropy > 0 {
			fmt.Fprintf(&b, ", Entropy: %g", r.Entropy)
		}
		if r.SecretGroup > 0 {
			fmt.Fprintf(&b, ", SecretGroup: %d", r.SecretGroup)
		}
		if len(allow) > 0 {
			fmt.Fprintf(&b, ", Allow: %s", list(allow))
		}
		if len(allowMatch) > 0 {
			fmt.Fprintf(&b, ", AllowMatch: %s", list(allowMatch))
		}
		if len(stop) > 0 {
			fmt.Fprintf(&b, ", Stopwords: %s", list(stop))
		}
		b.WriteString("},\n")
		kept++
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("gitleaks %s: %d rules kept, %d skipped by choice, %d skipped because Go regexp cannot compile them\n", *tag, kept, skipped, bad)
	for _, s := range skippedIDs {
		fmt.Println("  skipped", s)
	}
}

// quote prefers a raw string literal, which keeps regexes readable.
func quote(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return fmt.Sprintf("%q", s)
}

func list(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = quote(x)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
