//go:build ignore

// Command gen-rule-docs writes docs/what-it-checks.md from rules/*.yaml:
// the intro in intro.md, then every rule grouped by category, in the order
// the UI shows them. Run it from the repository root after changing a rule:
//
//	go run ./tools/gen-rule-docs/main.go
//
// CI runs it with -check and fails when the committed file is stale.
//
// It lives in the main module (the build tag keeps the tools module from
// compiling it), so it reads the rules exactly as the binary does and uses
// the real category mapping instead of a copy.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"log"
	"os"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/The-Last-Devops/security-warden/internal/engine"
	"github.com/The-Last-Devops/security-warden/internal/i18n"
	"github.com/The-Last-Devops/security-warden/internal/report"
	"github.com/The-Last-Devops/security-warden/rules"
)

const (
	introPath = "tools/gen-rule-docs/intro.md"
	outPath   = "docs/what-it-checks.md"
)

func main() {
	check := flag.Bool("check", false, "fail if "+outPath+" is not up to date instead of writing it")
	flag.Parse()

	rs, err := load()
	if err != nil {
		log.Fatal(err)
	}
	intro, err := os.ReadFile(introPath)
	if err != nil {
		log.Fatal(err)
	}
	out := render(string(intro), rs)

	if *check {
		cur, err := os.ReadFile(outPath)
		if err != nil || !bytes.Equal(cur, out) {
			log.Fatalf("%s is stale: run go run ./tools/gen-rule-docs/main.go and commit the result", outPath)
		}
		return
	}
	if err := os.WriteFile(outPath, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func load() ([]*engine.Rule, error) {
	files, err := fs.Glob(rules.FS, "*.yaml")
	if err != nil {
		return nil, err
	}
	var rs []*engine.Rule
	for _, f := range files {
		b, err := fs.ReadFile(rules.FS, f)
		if err != nil {
			return nil, err
		}
		var r engine.Rule
		dec := yaml.NewDecoder(bytes.NewReader(b))
		dec.KnownFields(true)
		if err := dec.Decode(&r); err != nil {
			return nil, fmt.Errorf("%s: %w", f, err)
		}
		if r.Tier == "" {
			r.Tier = "stable"
		}
		rs = append(rs, &r)
	}
	return rs, nil
}

func sevRank(s string) int {
	for i, v := range engine.Severities {
		if v == s {
			return i
		}
	}
	return len(engine.Severities)
}

// cell keeps a text on one table row: | would split the cell.
func cell(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.ReplaceAll(s, "|", `\|`)
}

func render(intro string, rs []*engine.Rule) []byte {
	byCat := map[string][]*engine.Rule{}
	sources := map[string]bool{}
	for _, r := range rs {
		c := report.Category(r.Source)
		byCat[c] = append(byCat[c], r)
		sources[r.Source] = true
	}

	var b strings.Builder
	b.WriteString("<!-- Generated by tools/gen-rule-docs from rules/*.yaml and tools/gen-rule-docs/intro.md. Do not edit by hand. -->\n\n")
	intro = strings.ReplaceAll(intro, "{{rules}}", fmt.Sprint(len(rs)))
	intro = strings.ReplaceAll(intro, "{{sources}}", fmt.Sprint(len(sources)))
	b.WriteString(strings.TrimRight(intro, "\n") + "\n")

	b.WriteString("\n## All rules\n\n")
	b.WriteString("Grouped as in the report and the web UI. `{field}` is filled in from the place that was found.\n")
	b.WriteString("Severity: critical, high, medium, low. Platforms: macOS, Linux, Windows.\n\n")
	for _, c := range report.Categories {
		if len(byCat[c]) > 0 {
			fmt.Fprintf(&b, "- [%s](#%s) (%d)\n", i18n.T("en", "cat."+c), c, len(byCat[c]))
		}
	}

	for _, c := range report.Categories {
		list := byCat[c]
		if len(list) == 0 {
			continue
		}
		sort.Slice(list, func(i, j int) bool {
			if a, b := sevRank(list[i].Severity), sevRank(list[j].Severity); a != b {
				return a < b
			}
			return list[i].ID < list[j].ID
		})
		srcs := map[string]bool{}
		for _, r := range list {
			srcs[r.Source] = true
		}
		var names []string
		for s := range srcs {
			names = append(names, s)
		}
		sort.Strings(names)

		fmt.Fprintf(&b, "\n<a id=\"%s\"></a>\n\n### %s\n\n", c, i18n.T("en", "cat."+c))
		fmt.Fprintf(&b, "Category `%s`, %d rules. Sources: %s.\n\n", c, len(list), "`"+strings.Join(names, "`, `")+"`")
		b.WriteString("| Rule | Severity | Platforms | Problem | Passes when |\n|---|---|---|---|---|\n")
		for _, r := range list {
			id := "`" + r.ID + "`"
			if r.Tier != "stable" {
				id += " (" + r.Tier + ")"
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", id, r.Severity, platforms(r.Platforms),
				cell(r.Title.Get("en")), cell(r.Check.Get("en")))
		}
	}
	return []byte(b.String())
}

func platforms(ps []string) string {
	name := map[string]string{"macos": "macOS", "linux": "Linux", "windows": "Windows"}
	order := []string{"macos", "linux", "windows"}
	var out []string
	for _, p := range order {
		for _, q := range ps {
			if q == p {
				out = append(out, name[p])
			}
		}
	}
	return strings.Join(out, ", ")
}
