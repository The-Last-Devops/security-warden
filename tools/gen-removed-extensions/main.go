// Command gen-removed-extensions turns the VS Marketplace list of removed
// extensions into internal/source/removedextensions_gen.go.
//
// Fetch the list first (never at scan time):
//
//	gh api repos/microsoft/vsmarketplace/contents/RemovedPackages.md -q .content | base64 -d > /tmp/RemovedPackages.md
//	cd tools && go run ./gen-removed-extensions -in /tmp/RemovedPackages.md -out ../internal/source/removedextensions_gen.go
//
// The list comes from https://github.com/microsoft/vsmarketplace,
// MIT License, Copyright (c) Microsoft Corporation.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

// kind maps the list's free-text removal type to the few kinds the rules
// use. Removals that say nothing about safety (spam, copyright, owner
// request, deprecated) are left out, so they never raise a finding.
func kind(t string) string {
	l := strings.ToLower(t)
	switch {
	case strings.Contains(l, "malware"), strings.Contains(l, "malicious"):
		return "Malware"
	case strings.Contains(l, "impersonation"), strings.Contains(l, "typo"):
		return "Impersonation"
	case strings.Contains(l, "untrustworthy"):
		return "Untrustworthy"
	case strings.Contains(l, "expired domain"):
		return "Expired domain"
	}
	return ""
}

func main() {
	in := flag.String("in", "", "RemovedPackages.md")
	out := flag.String("out", "", "output Go file")
	flag.Parse()
	if *in == "" || *out == "" {
		log.Fatal("usage: gen-removed-extensions -in RemovedPackages.md -out file.go")
	}
	f, err := os.Open(*in)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	m := map[string]string{}
	skipped := map[string]int{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		cols := strings.Split(strings.TrimSpace(sc.Text()), "|")
		if len(cols) < 4 {
			continue
		}
		id := strings.ToLower(strings.TrimSpace(cols[1]))
		typ := strings.TrimSpace(cols[3])
		if id == "" || id == "extension identifier" || strings.HasPrefix(id, "--") || !strings.Contains(id, ".") {
			continue
		}
		k := kind(typ)
		if k == "" {
			skipped[typ]++
			continue
		}
		// An extension removed twice keeps the worst reason.
		if m[id] != "Malware" {
			m[id] = k
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	if len(m) < 100 {
		log.Fatalf("only %d entries: did the table format change?", len(m))
	}
	ids := make([]string, 0, len(m))
	for id := range m {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/gen-removed-extensions; DO NOT EDIT.\n\n")
	b.WriteString("// Extensions removed from the VS Marketplace, from\n// https://github.com/microsoft/vsmarketplace (RemovedPackages.md),\n// MIT License, Copyright (c) Microsoft Corporation.\n\npackage source\n\n")
	b.WriteString("// removedExtensions maps a lower-case extension id to why the Marketplace\n// removed it: Malware, Impersonation, Untrustworthy or Expired domain.\nvar removedExtensions = map[string]string{\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "\t%q: %q,\n", id, m[id])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	counts := map[string]int{}
	for _, k := range m {
		counts[k]++
	}
	fmt.Printf("%d removed extensions kept %v; left out %v\n", len(m), counts, skipped)
}
