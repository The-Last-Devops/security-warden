package source

// Field is one fact that items of a source carry, for rule authors: rules
// read it as item.<name> in match and as {name} in texts.
type Field struct {
	Name string `json:"name"`
	Type string `json:"type"` // bool, number or string
	Desc string `json:"desc"`
}

// Info describes what a source collects: where it runs and the fields of
// its items. Tests check every rule against it, so the docs generated from
// it (docs/rule-sources.md, `security-warden rules sources`) stay true.
type Info struct {
	Platforms []string `json:"platforms"`
	Fields    []Field  `json:"fields"`
}

// FieldTypes are the types a field may have.
var FieldTypes = []string{"bool", "number", "string"}

